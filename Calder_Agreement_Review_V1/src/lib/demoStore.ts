export function localRead() {
  const raw = localStorage.getItem(LOCAL_KEY);
  if (!raw) {
    const value = cloneSeed();
    localStorage.setItem(LOCAL_KEY, JSON.stringify(value));
    return value;
  }
  return JSON.parse(raw) as Data;
}
